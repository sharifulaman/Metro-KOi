// Bundles assets/sim/station-to-station.html (the 3D "station to station"
// simulation) into src/data/simHtml.ts as a string, so the app ships it and
// can open it offline in a WebView. Re-run after editing the HTML:
//   npm run build:sim
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const html = readFileSync(`${root}assets/sim/station-to-station.html`, 'utf8');
const out = `// GENERATED by scripts/build-sim.mjs from assets/sim/station-to-station.html. Do not edit.
const html: string = ${JSON.stringify(html)};
export default html;
`;
writeFileSync(`${root}src/data/simHtml.ts`, out);
console.log(`simHtml.ts written (${(html.length / 1024).toFixed(1)} KB)`);

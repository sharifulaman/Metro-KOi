// Bundles assets/vendor/three.min.js (three.js r128, MIT) into
// src/components/map/GoogleMapView/threeSource.ts as a string, so the 3D map page
// carries its own copy of the library and works with no internet connection.
// Re-run after replacing the file:   npm run build:three
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = readFileSync(`${root}assets/vendor/three.min.js`, 'utf8');
const out = `// GENERATED by scripts/build-three.mjs from assets/vendor/three.min.js (three.js r128, MIT). Do not edit.
export const THREE_SRC: string = ${JSON.stringify(src)};
`;
writeFileSync(`${root}src/components/map/GoogleMapView/threeSource.ts`, out);
console.log(`threeSource.ts written (${(src.length / 1024).toFixed(0)} KB)`);
